"""Write results/observations.md: the key numbers of the saved run as plain tables.

    python observations.py

Reads results/measurements.json only. Every figure in REPORT.md comes from this file.
"""
import argparse
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent


def seconds(value):
    if value is None:
        return "–"
    for unit, scale in (("s", 1), ("ms", 1e3), ("µs", 1e6), ("ns", 1e9)):
        if abs(value) * scale >= 1 or unit == "ns":
            return f"{value * scale:.3g} {unit}"


def nanos(value):
    return seconds(None if value is None else value / 1e9)


def size(value):
    if value is None:
        return "–"
    return f"{value / 1048576:.3g} MiB" if value >= 1048576 else f"{value / 1024:.3g} KiB"


def number(value):
    return "–" if value is None else f"{value:,.0f}"


def table(head, rows):
    lines = ["| " + " | ".join(head) + " |", "|" + "|".join("---" if i == 0 else "---:" for i in range(len(head))) + "|"]
    return "\n".join(lines + ["| " + " | ".join(str(c) for c in row) + " |" for row in rows])


def replay_cell(row):
    if row is None:
        return "–"
    if row["status"] == "stopped":
        return f"stopped (> {row['stopped_after_seconds']:.0f} s, {row['events_completed']:,} events done)"
    return seconds(row.get("replay_seconds_median"))


def build(data):
    meta, settings = data["metadata"], data["metadata"]["settings"]
    seed = settings["seeds"][0]
    replay = {(r["scenario"], r["seed"], r["events"], r["version"]): r for r in data["replay"]}
    fixed = {(r["book_orders"], r["levels"], r["seed"], r["sale_pct"], r["version"]): r for r in data["fixed_book"]}
    scenarios = sorted({r["scenario"] for r in data["replay"]})
    sizes = sorted({r["events"] for r in data["replay"]})
    out = ["# Observations from the saved run", "",
           f"{meta['implementation']} {meta['python'].split()[0]} on {meta['platform']} ({meta['processor']}, "
           f"{meta['logical_cpus']} logical CPUs), started {meta['created_utc'][:19]} UTC. "
           f"Medians of {settings['repeats']} repeats. Limits: {settings['replay_limit_seconds']:.0f} s per replay, "
           f"{settings['sale_limit_seconds']:.0f} s per sale. Version A = unsorted lists with scans; "
           "version B = price levels, heaps and an order index. Generated by `observations.py`; do not edit by hand.", ""]

    out += [f"## Stream replay, seed {seed}", "",
            "Engine time for the whole stream. B and P are peak active orders and peak occupied price levels; F is maker fills.", ""]
    rows = []
    for scenario in scenarios:
        for count in sizes:
            a, b = replay.get((scenario, seed, count, "A")), replay.get((scenario, seed, count, "B"))
            if not (a or b):
                continue
            outcome = (b or {}).get("outcome") or (a or {}).get("outcome") or {}
            ta, tb = (a or {}).get("replay_seconds_median"), (b or {}).get("replay_seconds_median")
            rows.append([scenario, f"{count:,}", number(outcome.get("peak_active_orders")),
                         number(outcome.get("peak_price_levels")), number(outcome.get("fill_count")),
                         replay_cell(a), replay_cell(b), f"{ta / tb:.3g}×" if ta and tb else "–",
                         number((b or {}).get("throughput_events_per_second"))])
    out += [table(["Workload", "M", "Peak B", "Peak P", "F", "A replay", "B replay", "A ÷ B", "B events/s"], rows), ""]

    out += ["## Spread across seeds at the common sizes", "",
            "Smallest and largest median replay time among the seeds, per version.", ""]
    rows = []
    for scenario in scenarios:
        for count in settings["sizes"]:
            cells = []
            for version in "AB":
                values = [replay[k]["replay_seconds_median"] for k in replay
                          if k[0] == scenario and k[2] == count and k[3] == version and replay[k]["status"] == "ok"]
                stopped = sum(1 for k in replay if k[0] == scenario and k[2] == count and k[3] == version
                              and replay[k]["status"] == "stopped")
                text = f"{seconds(min(values))} – {seconds(max(values))}" if values else "–"
                cells.append(text + (f" ({stopped} stopped)" if stopped else ""))
            rows.append([scenario, f"{count:,}", *cells])
    out += [table(["Workload", "M", "A", "B"], rows), ""]

    out += ["## Runs stopped at a declared limit", ""]
    stopped = [r for r in data["replay"] + data["fixed_book"] if r["status"] == "stopped"]
    rows = [[r["experiment"], r["version"], r["scenario"], number(r.get("book_orders") or r["events"]), r["seed"],
             f"{r['sale_pct']}%" if r.get("sale_pct") else "–",
             f"{r['events_completed']:,} of {r['events']:,} events" if r["experiment"] == "replay"
             else f"sale not finished within {r['sale_limit_seconds']:.0f} s"] for r in stopped]
    out += [table(["Experiment", "Version", "Workload", "Size", "Seed", "Sale", "Reached"], rows) if rows
            else "None.", "", f"{len(stopped)} of {len(data['replay']) + len(data['fixed_book'])} cells. "
            "No value is estimated for a stopped run.", ""]

    out += [f"## Build phase and the phase after it, seed {seed}", ""]
    rows = [[r["scenario"], f"{r['events']:,}", r["version"], f"{r['build_events']:,}",
             seconds(r["build_seconds_median"]), seconds(r["tail_seconds_median"])]
            for r in sorted(data["replay"], key=lambda r: (r["scenario"], r["events"], r["version"]))
            if r["seed"] == seed and r.get("build_seconds_median") is not None]
    out += [table(["Workload", "M", "Version", "Build events", "Build", "After build"], rows), ""]

    out += [f"## One market sell against a fresh bid book, {settings['levels']:,} prices offered, seed {seed}", "",
            "Fills, levels visited and the unfilled remainder are the same for both versions.", ""]
    rows = []
    for orders in sorted({k[0] for k in fixed if k[1] == settings["levels"] and k[2] == seed}):
        for pct in settings["sale_percents"]:
            a, b = fixed.get((orders, settings["levels"], seed, pct, "A")), fixed.get((orders, settings["levels"], seed, pct, "B"))
            o = (b or {}).get("outcome") or (a or {}).get("outcome") or {}
            ca = (a or {}).get("counters") or {}
            sa, sb = (a or {}).get("sell_seconds_median"), (b or {}).get("sell_seconds_median")
            rows.append([f"{orders:,}", f"{pct}%", number(o.get("fill_count")), number(o.get("price_levels_visited")),
                         f"{o['unfilled_qty_units'] / 1e8:.6g} BTC" if o else "–",
                         "stopped" if a and a["status"] == "stopped" else seconds(sa), seconds(sb),
                         f"{sa / sb:.3g}×" if sa and sb else "–",
                         number(ca.get("records_examined_best", 0) + ca.get("records_examined_remove", 0)) if ca else "–",
                         number(((b or {}).get("counters") or {}).get("heap_pops")),
                         seconds((a or {}).get("construction_seconds_median")),
                         seconds((b or {}).get("construction_seconds_median"))])
    out += [table(["N bids", "Sale", "Fills", "Levels visited", "Unfilled", "A sell", "B sell", "A ÷ B",
                   "A records examined", "B heap pops", "A construct", "B construct"], rows), ""]

    cseed, corders = settings["concentration_seeds"][0], settings["concentration_orders"]
    out += [f"## Queue concentration: N = {corders:,} bids, 100% sale, seed {cseed}", ""]
    rows = []
    for levels in sorted({k[1] for k in fixed if k[0] == corders and k[2] == cseed}):
        a, b = fixed.get((corders, levels, cseed, 100, "A")), fixed.get((corders, levels, cseed, 100, "B"))
        o = (b or {}).get("outcome") or {}
        rows.append([f"{levels:,}", number(o.get("peak_price_levels")),
                     "stopped" if a and a["status"] == "stopped" else seconds((a or {}).get("sell_seconds_median")),
                     seconds((b or {}).get("sell_seconds_median")),
                     seconds((a or {}).get("construction_seconds_median")),
                     seconds((b or {}).get("construction_seconds_median")),
                     "yes" if all((r or {}).get("outcome", {}) and r["outcome"]["matches_sorted_fill_plan"]
                                  for r in (a, b) if r and r.get("outcome")) else "NO"])
    out += [table(["Prices offered", "P occupied", "A sell", "B sell", "A construct", "B construct",
                   "Fills equal sorted plan"], rows), ""]

    out += [f"## Processing latency per event, seed {seed}", "",
            "Nearest-rank percentiles over all events of the stream; first and last tenth show the effect of book growth.", ""]
    rows = []
    for scenario in scenarios:
        for count in settings["sizes"]:
            for version in "AB":
                lat = (replay.get((scenario, seed, count, version)) or {}).get("latency")
                if not lat:
                    continue
                o = lat["overall"]
                rows.append([scenario, f"{count:,}", version, nanos(o["p50_ns"]), nanos(o["p95_ns"]), nanos(o["p99_ns"]),
                             nanos(lat["first_10pct"]["p50_ns"]), nanos(lat["last_10pct"]["p50_ns"]),
                             nanos(lat["last_10pct"]["p99_ns"])])
    out += [table(["Workload", "M", "Version", "Median", "p95", "p99", "Median, first 10%", "Median, last 10%",
                   "p99, last 10%"], rows), ""]

    out += [f"## Traced memory, seed {seed}", "",
            "Peak during the replay and value at its end, with the number of orders still active.", ""]
    rows = []
    for scenario in scenarios:
        for count in sizes:
            for version in "AB":
                row = replay.get((scenario, seed, count, version)) or {}
                mem, o = row.get("memory"), row.get("outcome") or {}
                if not mem:
                    continue
                stored = (o.get("final_storage") or {}).get("stored_entries")
                peak_b = o.get("peak_active_orders")
                rows.append([scenario, f"{count:,}", version, number(peak_b), number(o.get("final_active_orders")),
                             size(mem["peak_bytes"]), size(mem["final_current_bytes"]),
                             f"{mem['peak_bytes'] / peak_b:,.0f}" if peak_b else "–", number(stored)])
    out += [table(["Workload", "M", "Version", "Peak B", "Active at end", "Peak traced", "Traced at end",
                   "Peak bytes per peak order", "Stored entries at end"], rows), ""]

    pairs = [(a, replay.get((a["scenario"], a["seed"], a["events"], "B"))) for a in data["replay"] if a["version"] == "A"]
    comparable = [(a, b) for a, b in pairs if a.get("outcome") and b and b.get("outcome")]
    equal = sum(a["outcome"]["results_sha256"] == b["outcome"]["results_sha256"]
                and a["outcome"]["book_sha256"] == b["outcome"]["book_sha256"] for a, b in comparable)
    sales = [r for r in data["fixed_book"] if r.get("outcome")]
    out += ["## Agreement", "",
            f"- Stream workloads where both versions finished: {len(comparable)} of {len(pairs)}; identical result "
            f"stream and final book in {equal} of them (SHA-256 over every event result and over the final inspection).",
            f"- Completed single sales: {len(sales)}; equal to the independently sorted fill plan in "
            f"{sum(r['outcome']['matches_sorted_fill_plan'] for r in sales)}.",
            "- Worked example: " + "; ".join(f"version {w['version']} {'matches' if w['matches_expected'] else 'DOES NOT match'}"
                                             f" ({w['gross_proceeds_usd']} dollars)" for w in data["worked_example"]) + ".", ""]
    return "\n".join(out)


def tuning_section(tuning):
    rows = [[r["workload"], f"{r['events']:,}", *(seconds(r["median_seconds"][e]) for e in tuning["engines"]),
             f"{r['ns_per_event']['B']:,.0f} ns", f"{r['b_time_as_share_of_original']:.2f}",
             f"{r['b_time_as_share_of_b1']:.2f}"] for r in tuning["rows"]]
    return "\n".join([
        "## Second revision step: B1 against the submitted version B", "",
        f"From `tuning.py`: median of {tuning['repeats']} interleaved replays in one process, seed {tuning['seed']}. "
        "\"B1 original\" is the first revision behind the event envelope as first written; \"B1\" is the same book "
        "behind the current envelope. Identical results were checked event by event before timing.", "",
        table(["Workload", "Events", *tuning["engines"], "B per event", "B ÷ B1 original", "B ÷ B1"], rows), ""])


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--results", type=Path, default=HERE / "results")
    args = parser.parse_args()
    data = json.loads((args.results / "measurements.json").read_text(encoding="utf-8"))
    text = build(data)
    tuning = args.results / "tuning.json"
    if tuning.exists():
        text += "\n" + tuning_section(json.loads(tuning.read_text(encoding="utf-8")))
    (args.results / "observations.md").write_text(text, encoding="utf-8", newline="\n")
    print(f"Wrote {args.results / 'observations.md'}")


if __name__ == "__main__":
    main()
